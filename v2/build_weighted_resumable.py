"""Version weighted checkpoint solver separately from frozen unweighted runs."""
from pathlib import Path
def main():
    root=Path(__file__).resolve().parent
    s=(root/'resumable_losses.py').read_text(encoding='utf-8')
    s=s.replace('checkpoint_every=100):','checkpoint_every=100,sample_weight=None):',1)
    s=s.replace("    identity=hashlib.sha256(json.dumps([run_id,asdict(config)],sort_keys=True).encode()).hexdigest()",
        "    w=base.normalize_weights(sample_weight,len(y))\n    weight_hash=hashlib.sha256(w.tobytes()).hexdigest()\n    identity=hashlib.sha256(json.dumps([run_id,asdict(config),weight_hash],sort_keys=True).encode()).hexdigest()",1)
    s=s.replace('ys=y/scale;w=np.ones(len(y))','ys=y/scale',1)
    s=s.replace('base.fit_linear_loss(x,y,config=config)','base.fit_linear_loss(x,y,sample_weight=w,config=config)',1)
    # In ADMM only soft threshold uses sample weights; quadratic constraint is unweighted.
    s=s.replace('matrix=rho*base._gram(x,w,config.chunk_rows)','matrix=rho*base._gram(x,np.ones(len(y)),config.chunk_rows)',1)
    s='# Generated by build_weighted_resumable.py; frozen reference preserved.\n'+s
    (root/'weighted_resumable_losses.py').write_text(s,encoding='utf-8')
if __name__=='__main__':main()
